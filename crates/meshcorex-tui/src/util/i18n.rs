//! Système i18n simple pour la TUI.
//!
//! Utilisation : `use crate::util::i18n::t; let label = t("tab.connection");`
//!
//! La langue courante est lue dynamiquement à chaque appel de `t()` depuis un
//! `RwLock` statique. Un changement via [`set_lang`] est visible immédiatement
//! dans les rendus suivants — pas besoin de redémarrer l'app.
//!
//! Fallback : si une clé n'existe pas dans la langue courante, on essaie la
//! langue par défaut (FR), et en dernier recours on retourne la clé elle-même.

use std::sync::RwLock;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Fr,
    En,
}

impl Lang {
    pub fn all() -> [Lang; 2] {
        [Lang::Fr, Lang::En]
    }

    pub fn code(&self) -> &'static str {
        match self {
            Lang::Fr => "fr",
            Lang::En => "en",
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            Lang::Fr => "Français",
            Lang::En => "English",
        }
    }

    pub fn from_code(code: &str) -> Lang {
        match code {
            "en" | "en-US" | "en-GB" => Lang::En,
            _ => Lang::Fr,
        }
    }
}

static CURRENT_LANG: RwLock<Lang> = RwLock::new(Lang::Fr);

pub fn current_lang() -> Lang {
    *CURRENT_LANG.read().expect("i18n lock poisoned")
}

pub fn set_lang(lang: Lang) {
    if let Ok(mut w) = CURRENT_LANG.write() {
        *w = lang;
    }
}

/// Traduit une clé vers la chaîne de la langue courante. Retourne la clé elle-même
/// si aucune traduction n'est disponible (utile en debug).
pub fn t(key: &str) -> String {
    let lang = current_lang();
    translate(lang, key)
        .or_else(|| translate(Lang::Fr, key))
        .map(|s| s.to_string())
        .unwrap_or_else(|| key.to_string())
}

